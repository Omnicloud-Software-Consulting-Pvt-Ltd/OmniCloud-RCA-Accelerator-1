/**
 * GLOBAL TAX RATE LIBRARY — reference data model (client + server safe, no Salesforce imports).
 *
 * A reference rate is NOT a Salesforce record and NOT a legal tax determination. It's a reusable, sourced, versioned description
 * of a rate in a jurisdiction that can prefill the existing Salesforce Tax Rate create form. Design rules:
 *  · No uniqueness on country/state: many rates per jurisdiction (tax types, codes, components, classifications, periods).
 *  · Tax types/structures/components are open strings (catalog suggestions only) — a new structure needs no model change.
 *  · Jurisdictions use ISO 3166-1 alpha-2 countries and ISO 3166-2 subdivision codes; a country-level rate has no subdivision.
 *  · Lifecycle: draft / published / archived is stored; Active / Upcoming / Expired is DERIVED from the effective dates.
 *  · History is never overwritten: a rate change closes the old version (Effective To) and adds a new version.
 */

export type JurisdictionLevel = "country" | "subdivision" | "locality";
export type RateCalculation = "percentage" | "fixed-amount" | "percentage-plus-fixed" | "tiered";
/**
 * verified — the rate was confirmed against the cited official source by an automated re-read of that source (or an official API);
 * partially-verified — official source cited with a verbatim quote captured when it was read, but the automated re-check couldn't
 *   confirm it (page unavailable / script-rendered / PDF); unverified — no confirmed official source; needs-review — flagged by a user.
 */
export type VerificationStatus = "verified" | "partially-verified" | "unverified" | "needs-review";
export type Lifecycle = "draft" | "published" | "archived";
/** Derived from lifecycle + effective dates (see statusOf). */
export type EffectiveStatus = "Active" | "Upcoming" | "Expired" | "Draft" | "Archived";

export interface Jurisdiction {
  /** ISO 3166-1 alpha-2, e.g. "IN". */
  countryCode: string;
  countryName: string;
  /** ISO 3166-2 code, e.g. "IN-AP" — null for a country-level rate (never invented). */
  subdivisionCode: string | null;
  subdivisionName: string | null;
  level: JurisdictionLevel;
  /** Optional region / locality (city, county, municipality) — free text metadata. */
  locality: string | null;
}

export interface TaxIdentity {
  /** The code Salesforce Tax Rates / Treatments match on (e.g. "GST18"). */
  taxCode: string;
  taxName: string;
  /** e.g. GST, VAT, Sales Tax, Excise — open string. */
  taxType: string;
  /** e.g. "GST (single)", "HST", "GST + QST", "CGST + SGST" — open string. */
  taxStructure: string;
  /** e.g. "CGST", "SGST", "QST" — null when the rate isn't one component of a combined structure. */
  taxComponent: string | null;
  taxAuthority: string | null;
  /** Rate category — e.g. Standard, Reduced, Super-reduced, Parking, Zero, Exempt (open string). */
  taxCategory: string | null;
  /** The tax code exactly as the official source publishes it (null when the source has none). */
  officialTaxCode?: string | null;
  /** True when `taxCode` was generated by the library (the source publishes no code) — never presented as an official code. */
  taxCodeGenerated?: boolean;
}

export interface RateDefinition {
  /** Percentage, e.g. 18 means 18 %. Null only for fixed-amount taxes. */
  ratePercent: number | null;
  fixedAmount: number | null;
  fixedAmountCurrency: string | null;
  minRatePercent: number | null;
  maxRatePercent: number | null;
  calculation: RateCalculation;
  /** Applied on top of other components (e.g. a cess on tax-inclusive base). */
  compound: boolean;
  /** Order among components of one structure (1 = first). */
  componentOrder: number | null;
}

export interface Classification {
  /** e.g. an HSN/SAC code, a tariff code, or the org's own code. */
  code: string | null;
  /** e.g. "HSN", "SAC", "UNSPSC", "Internal" — open string. */
  system: string | null;
  productCategory: string | null;
  serviceCategory: string | null;
  description: string | null;
  conditions: string | null;
  transactionType: string | null;
  placeOfSupply: string | null;
}

export interface Effectivity {
  /** ISO date YYYY-MM-DD. */
  effectiveFrom: string;
  /** ISO date, inclusive; null = open-ended. */
  effectiveTo: string | null;
}

export interface SourceInfo {
  sourceName: string | null;
  /** Organisation that publishes the source (e.g. "HM Revenue & Customs"). */
  sourceOrganization?: string | null;
  sourceUrl: string | null;
  sourceReference: string | null;
  notes: string | null;
  verification: VerificationStatus;
  lastVerifiedAt: string | null;
}

export interface AuditEntry { at: string; action: "created" | "updated" | "versioned" | "superseded" | "archived" | "restored" | "imported" | "seeded" | "duplicated"; detail: string }

export interface TaxRateReference {
  /** Stable identifier (never reused). */
  id: string;
  /** All versions of one rate share a lineage id; `version` increments. */
  lineageId: string;
  version: number;
  /** The version this one replaced (null for the first). */
  supersedesId: string | null;
  jurisdiction: Jurisdiction;
  tax: TaxIdentity;
  rate: RateDefinition;
  classification: Classification;
  effective: Effectivity;
  source: SourceInfo;
  lifecycle: Lifecycle;
  /** "seed:<dataset>" for records shipped with the app, "user", or "import:<file>". */
  origin: string;
  createdAt: string;
  updatedAt: string;
  history: AuditEntry[];
}

/** Editable payload (create / edit / import row). */
export type TaxRateInput = Pick<TaxRateReference, "jurisdiction" | "tax" | "rate" | "classification" | "effective" | "source" | "lifecycle">;

/** Suggestions for the open tax-type / structure fields (never a restriction). */
export const KNOWN_TAX_TYPES = ["GST", "CGST", "SGST", "IGST", "UTGST", "Cess", "HST", "PST", "RST", "QST", "VAT", "Sales Tax", "Use Tax", "Excise Tax", "Consumption Tax", "Service Tax", "Regional Tax", "Municipal Tax"] as const;

export const EFFECTIVE_STATUSES: EffectiveStatus[] = ["Active", "Upcoming", "Expired", "Draft", "Archived"];

/** The identity two versions/records must share to be "the same rate" (duplicate / overlapping-period checks). */
export function identityKey(r: Pick<TaxRateReference, "jurisdiction" | "tax" | "classification">): string {
  const n = (v: string | null | undefined) => (v ?? "").trim().toLowerCase();
  return [
    n(r.jurisdiction.countryCode), n(r.jurisdiction.subdivisionCode), n(r.jurisdiction.locality),
    n(r.tax.taxType), n(r.tax.taxCode), n(r.tax.taxComponent),
    n(r.classification.system), n(r.classification.code), n(r.classification.transactionType),
  ].join("|");
}

export function todayIso(d = new Date()): string { return d.toISOString().slice(0, 10); }

/** Active / Upcoming / Expired from the dates; Draft / Archived from the lifecycle. */
export function statusOf(r: Pick<TaxRateReference, "lifecycle" | "effective">, today = todayIso()): EffectiveStatus {
  if (r.lifecycle === "archived") return "Archived";
  if (r.lifecycle === "draft") return "Draft";
  if (r.effective.effectiveFrom > today) return "Upcoming";
  if (r.effective.effectiveTo && r.effective.effectiveTo < today) return "Expired";
  return "Active";
}

/** Inclusive date-range overlap (null end = open). */
export function periodsOverlap(a: Effectivity, b: Effectivity): boolean {
  const aEnd = a.effectiveTo ?? "9999-12-31", bEnd = b.effectiveTo ?? "9999-12-31";
  return a.effectiveFrom <= bEnd && b.effectiveFrom <= aEnd;
}

export function rateLabel(r: RateDefinition): string {
  const pct = r.ratePercent !== null ? `${Number(r.ratePercent.toFixed(4))}%` : null;
  const fixed = r.fixedAmount !== null ? `${r.fixedAmount}${r.fixedAmountCurrency ? ` ${r.fixedAmountCurrency}` : ""}` : null;
  return [pct, fixed].filter(Boolean).join(" + ") || "—";
}
