function describeField(f: BillingModuleSchema["fields"][number]): string {
  const parts: string[] = [f.type];
  if (f.required) parts.push("REQUIRED");
  if (f.length && (f.type === "string" || f.type === "textarea")) parts.push(`max ${f.length} chars`);
  if (f.picklistValues.length) parts.push(`values: ${f.picklistValues.map(p => p.value).join(" | ")}`);
  if (f.type === "reference") parts.push(`→ ${f.referenceTo.join("/")}`);
  if (f.controllerName) parts.push(`depends on ${f.controllerName}`);
  return `  - ${f.name} (${f.label}): ${parts.join(", ")}`;
}

function describeSchema(schema: BillingModuleSchema, heading: string, parentField: string | null): string {
  const fields = schema.fields.filter(f => f.createable && !f.system && f.name !== parentField);
  return [`${heading} ${schema.sobject} (${schema.label})`, ...fields.map(describeField)].join("\n");
}

async function collectChildSchemas(client: SalesforceClient, schema: BillingModuleSchema, depth: number): Promise<{ schema: BillingModuleSchema; parentField: string; parentSobject: string; depth: number }[]> {
  if (depth >= 2) return [];
  const out: { schema: BillingModuleSchema; parentField: string; parentSobject: string; depth: number }[] = [];
  for (const c of schema.children) {
    try {
      const childSchema = await getModuleSchema(client, c.moduleKey);
      out.push({ schema: childSchema, parentField: c.parentField, parentSobject: schema.sobject, depth: depth + 1 });
      out.push(...(await collectChildSchemas(client, childSchema, depth + 1)));
    } catch {
      // Child unavailable — the AI simply isn't told about it.
    }
  }
  return out;
}

