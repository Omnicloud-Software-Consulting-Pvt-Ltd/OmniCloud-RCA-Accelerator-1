export const BILLING_AI_KEY_MESSAGE =
  "Billing AI analysis is unavailable because the configured AI API key is invalid or missing. Complete Setup to add a valid Anthropic API key.";

export function describeBillingAiError(err: unknown): { status: number; message: string } {
  if (err instanceof Anthropic.AuthenticationError) return { status: 503, message: BILLING_AI_KEY_MESSAGE };
  if (err instanceof Anthropic.APIError) return { status: 502, message: `Billing AI analysis failed: ${err.message}` };
  return { status: 500, message: err instanceof Error ? err.message : "Billing AI analysis failed" };
}

