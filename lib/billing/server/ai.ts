const CLASSIFY_PROMPT = (modules: string[]) => `You route Salesforce Revenue Cloud Billing requests. Pick the single billing object the user wants to CREATE.
Available modules (key: description):
${modules.join("\n")}
Output ONLY JSON: {"moduleKey": "<one key from the list>", "confidence": 0.0-1.0, "reason": "short"}. If none fits, use {"moduleKey": null, "confidence": 0, "reason": "..."}.`;

function parseJsonObject(text: string): Record<string, unknown> {
  try {
    return JSON.parse(text);
  } catch {
    const match = text.match(/\{[\s\S]*\}/);
    if (!match) throw new Error("The AI didn't return a structured configuration. Try describing the billing setup in more detail.");
    return JSON.parse(match[0]);
  }
}

export async function callClaude(anthropic: Anthropic, system: string, prompt: string, maxTokens: number): Promise<Record<string, unknown>> {
  const msg = await anthropic.messages.create({
    model: CLAUDE_MODEL,
    max_tokens: maxTokens,
    system,
    messages: [{ role: "user", content: prompt }],
  });
  const text = msg.content.find(b => b.type === "text");
  return parseJsonObject(text && text.type === "text" ? text.text.trim() : "");
}

/** Step 1 (only when no module was chosen yet): identify which billing object the prompt is about. */
export async function identifyBillingModule(client: SalesforceClient, anthropic: Anthropic, prompt: string): Promise<{ moduleKey: string | null; confidence: number; reason: string }> {
  const resolved = await resolveAllModules(client);
  const available = BILLING_MODULES.filter(m => resolved.get(m.key)?.createable);
  const out = await callClaude(anthropic, CLASSIFY_PROMPT(available.map(m => `${m.key}: ${m.singular} — ${m.description}`)), prompt, 300);
  const key = typeof out.moduleKey === "string" && available.some(m => m.key === out.moduleKey) ? out.moduleKey : null;
  return { moduleKey: key, confidence: typeof out.confidence === "number" ? out.confidence : 0, reason: typeof out.reason === "string" ? out.reason : "" };
}

type AiRecord = { objectType?: unknown; fields?: unknown; relationships?: unknown; childRecords?: unknown };

let keyCounter = 0;
const newKey = () => `k${Date.now().toString(36)}${(keyCounter++).toString(36)}`;

interface NormalizeStats { fieldsExtracted: number; fieldsDropped: number; refsResolved: number; refsUnresolved: number; idsRejected: number }

async function normalizeRecord(
  client: SalesforceClient, schema: BillingModuleSchema, ai: AiRecord, depth: number,
  warnings: string[], stats: NormalizeStats,
): Promise<BillingDraftRecord> {
  const draft: BillingDraftRecord = { key: newKey(), moduleKey: schema.moduleKey, fields: {}, references: {}, unresolved: {}, children: [] };
  const byName = new Map(schema.fields.map(f => [f.name.toLowerCase(), f]));
  const rawFields = (ai.fields && typeof ai.fields === "object" ? ai.fields : {}) as Record<string, unknown>;
  const rawRels = { ...((ai.relationships && typeof ai.relationships === "object" ? ai.relationships : {}) as Record<string, unknown>) };

  for (const [name, value] of Object.entries(rawFields)) {
    const field = byName.get(name.toLowerCase());
    if (!field) { warnings.push(`Ignored "${name}" — no such field on ${schema.label} in this org.`); stats.fieldsDropped++; continue; }
    if (field.type === "reference") { rawRels[field.name] = value; continue; }
    if (!field.createable || field.system) { warnings.push(`Ignored ${field.label} — it's read-only in this org.`); stats.fieldsDropped++; continue; }
    const coerced = coerceFieldValue(field, value);
    if (!coerced.ok) { warnings.push(`${schema.label}: ${coerced.reason}`); stats.fieldsDropped++; continue; }
    if (coerced.value !== null) { draft.fields[field.name] = coerced.value; stats.fieldsExtracted++; }
  }

  for (const [name, value] of Object.entries(rawRels)) {
    const field = byName.get(name.toLowerCase());
    if (!field || field.type !== "reference") { warnings.push(`Ignored relationship "${name}" — not a lookup on ${schema.label}.`); continue; }
    if (!field.createable) continue;
    const spec = (typeof value === "string" ? { name: value } : value) as { name?: unknown; object?: unknown } | null;
    const searched = typeof spec?.name === "string" ? spec.name.trim() : "";
    if (!searched) continue;
    // Real Ids are 15/18 alphanumerics with a zero-padded run after the key prefix (e.g. "0Tt5g00000AbCdE").
    if (SALESFORCE_ID.test(searched) && /0{2,}/.test(searched)) {
      stats.idsRejected++;
      warnings.push(`The AI returned a raw Id for ${field.label}; Ids are never trusted from AI output — please pick the record with the lookup.`);
      continue;
    }
    const target = typeof spec?.object === "string" && field.referenceTo.includes(spec.object) ? spec.object : field.referenceTo[0];
    if (!target) continue;
    try {
      const resolution = await resolveReferenceByName(client, target, searched);
      if (resolution.outcome === "resolved") {
        draft.references[field.name] = resolution.match;
        stats.refsResolved++;
        if (resolution.matchType === "partial") warnings.push(`${field.label}: "${searched}" matched "${resolution.match.name}" — confirm this is the right record.`);
      } else {
        draft.unresolved![field.name] = { searchedName: searched, sobject: target, candidates: resolution.candidates };
        stats.refsUnresolved++;
      }
    } catch (err) {
      draft.unresolved![field.name] = { searchedName: searched, sobject: target, candidates: [] };
      stats.refsUnresolved++;
      warnings.push(`Couldn't search ${target} for "${searched}": ${err instanceof Error ? err.message : "lookup failed"}.`);
    }
  }

  const rawChildren = Array.isArray(ai.childRecords) ? (ai.childRecords as AiRecord[]) : [];
  if (depth < 2) {
    for (const child of rawChildren) {
      const objectType = typeof child.objectType === "string" ? child.objectType : "";
      const rel = schema.children.find(c => c.sobject.toLowerCase() === objectType.toLowerCase());
      if (!rel) { warnings.push(`Skipped a child "${objectType || "record"}" — it can't be created under ${schema.label} in this org.`); continue; }
      try {
        const childSchema = await getModuleSchema(client, rel.moduleKey);
        draft.children.push(await normalizeRecord(client, childSchema, child, depth + 1, warnings, stats));
      } catch {
        warnings.push(`Skipped a ${rel.singular} — its object couldn't be loaded.`);
      }
    }
  } else if (rawChildren.length) {
    warnings.push("Skipped records nested deeper than two levels.");
  }

  if (Object.keys(draft.unresolved!).length === 0) delete draft.unresolved;
  return draft;
}

async function normalizeLinks(client: SalesforceClient, schema: BillingModuleSchema, rawLinks: unknown, warnings: string[]): Promise<BillingDraftLink[]> {
  const requested = Array.isArray(rawLinks) ? (rawLinks as { sobject?: unknown; field?: unknown; recordNames?: unknown }[]) : [];
  const links: BillingDraftLink[] = schema.inboundLinks.map(l => ({ key: newKey(), sobject: l.sobject, field: l.field, label: l.label, valueSource: l.valueSource, targets: [], enabled: false }));
  for (const req of requested) {
    const link = links.find(l => l.sobject === req.sobject && l.field === req.field);
    if (!link) continue;
    const names = Array.isArray(req.recordNames) ? req.recordNames.filter((n): n is string => typeof n === "string" && !!n.trim()) : [];
    for (const name of names.slice(0, 10)) {
      try {
        const r = await resolveReferenceByName(client, link.sobject, name);
        if (r.outcome === "resolved") link.targets.push(r.match as BillingReferenceValue);
        else warnings.push(`${link.sobject === "Product2" ? "Product" : link.sobject} "${name}" ${r.outcome === "ambiguous" ? `matched ${r.candidates.length} records — pick the right one in "${link.label}"` : "could not be found in Salesforce"}.`);
      } catch {
        warnings.push(`Couldn't look up "${name}" for "${link.label}".`);
      }
    }
    link.enabled = link.targets.length > 0;
  }
  return links;
}


const refIds = (d: BillingDraftRecord) => Object.fromEntries(Object.entries(d.references).filter(([, v]) => !!v).map(([k, v]) => [k, v!.id]));

/**
 * Registry `defaults` (Salesforce platform rules Describe can't express), applied only where the
 * rule holds — e.g. treatment items of a NON-milestone treatment — and only to fields the model
 * left empty. Each one is reported as an assumption so the user sees it before creating.
 */
async function applyDefaultsTree(client: SalesforceClient, draft: BillingDraftRecord, parent: BillingDraftRecord | null, assumptions: string[]): Promise<void> {
  const def = getBillingModule(draft.moduleKey);
  const schema = await getModuleSchema(client, draft.moduleKey).catch(() => null);
  if (def?.defaults && schema) {
    const flag = await parentFlagFor(client, def, schema, { ...draft.fields, ...refIds(draft) }, parent ? { node: { moduleKey: parent.moduleKey, payload: parent.fields } } : null);
    for (const [name, value] of Object.entries(applicableDefaults(draft.moduleKey, schema.fields, flag))) {
      if (draft.fields[name] !== undefined && draft.fields[name] !== null && draft.fields[name] !== "") continue;
      draft.fields[name] = value;
      const field = schema.fields.find(f => f.name === name);
      const valueLabel = field?.picklistValues.find(p => p.value === value)?.label ?? String(value);
      assumptions.push(`${field?.label ?? name} set to ${valueLabel} — ${def.defaultsReason ?? "required by Salesforce for this configuration."}`);
    }
  }
  for (const child of draft.children) await applyDefaultsTree(client, child, draft, assumptions);
}

type AnalysisContext = BillingAnalysisResult["context"];

/**
 * Product named in the prompt → the product's REAL billing chain read from Salesforce
 * (Product2.BillingPolicyId → BillingPolicy.DefaultBillingTreatmentId), used to fill the lookups
 * the product implies. Relationship names come from Describe; nothing is written, and any update
 * to an existing record is only pre-filled as an opt-in link the user must enable.
 */
async function applyProductContext(
  client: SalesforceClient, schema: BillingModuleSchema, draft: BillingDraftRecord, links: BillingDraftLink[],
  productName: string, warnings: string[], assumptions: string[], unresolved: BillingAnalysisResult["unresolvedReferences"],
): Promise<AnalysisContext> {
  const ctx: AnalysisContext = { productName, product: null, productBillingPolicy: null, productDefaultTreatment: null };
  let res: Awaited<ReturnType<typeof resolveReferenceByName>>;
  try {
    res = await resolveReferenceByName(client, "Product2", productName);
  } catch {
    warnings.push(`Couldn't search Products for "${productName}".`);
    return ctx;
  }
  if (res.outcome !== "resolved") {
    unresolved.push({ path: "", field: null, label: "Product", searchedName: productName, sobject: "Product2", candidates: res.candidates, createAsChildModule: null });
    warnings.push(res.outcome === "ambiguous" ? `Product "${productName}" matched ${res.candidates.length} products — pick the right one.` : `Product "${productName}" was not found in Salesforce.`);
    return ctx;
  }
  const product = res.match;
  ctx.product = product;

  // The product's current billing chain, through the org's real relationship names (never guessed).
  const productDescribe = await billingDescribe(client, "Product2");
  const policyField = productDescribe.fields.find(f => f.name === "BillingPolicyId" && f.type === "reference");
  if (policyField?.relationshipName) {
    const policyDescribe = await billingDescribe(client, "BillingPolicy").catch(() => null);
    const defField = policyDescribe?.fields.find(f => f.name === "DefaultBillingTreatmentId" && f.type === "reference");
    const rel = policyField.relationshipName;
    const select = ["Id", policyField.name, `${rel}.Name`, ...(defField?.relationshipName ? [`${rel}.${defField.name}`, `${rel}.${defField.relationshipName}.Name`] : [])];
    try {
      const q = await client.query<Record<string, unknown>>(`SELECT ${select.join(", ")} FROM Product2 WHERE Id = '${soqlEscape(product.id)}' LIMIT 1`);
      const row = q.records[0];
      const policyId = row?.[policyField.name] as string | null | undefined;
      const policy = row?.[rel] as Record<string, unknown> | null | undefined;
      if (policyId && policy) {
        ctx.productBillingPolicy = { id: policyId, name: String(policy.Name), sobject: "BillingPolicy", moduleKey: "billing-policies" };
        const tId = defField ? (policy[defField.name] as string | null) : null;
        const t = defField?.relationshipName ? (policy[defField.relationshipName] as Record<string, unknown> | null) : null;
        if (tId && t) ctx.productDefaultTreatment = { id: tId, name: String(t.Name), sobject: "BillingTreatment", moduleKey: "billing-treatments" };
      }
    } catch {
      warnings.push(`Couldn't read ${product.name}'s current billing configuration.`);
    }
  }

  const productLink = links.find(l => l.sobject === "Product2" && l.field === "BillingPolicyId");
  const addTarget = (l: BillingDraftLink, v: BillingReferenceValue) => { if (!l.targets.some(t => t.id === v.id)) l.targets.push(v); };
  const has = (field: string) => !!draft.references[field] || !!draft.unresolved?.[field] || !!draft.childReferences?.[field];

  if (schema.moduleKey === "billing-policies" && productLink) {
    addTarget(productLink, product);
    productLink.enabled = true;
    assumptions.push(`${product.name} will be assigned to this new Billing Policy (Product → Billing Policy).`);
    if (ctx.productBillingPolicy) warnings.push(`${product.name} currently uses Billing Policy "${ctx.productBillingPolicy.name}" — creating this policy will replace it. Untick "${productLink.label}" to keep it.`);
  }

  if (schema.moduleKey === "billing-treatments") {
    const policyMeta = schema.fields.find(f => f.name === "BillingPolicyId" && f.createable);
    if (policyMeta && !has("BillingPolicyId") && ctx.productBillingPolicy) {
      draft.references.BillingPolicyId = ctx.productBillingPolicy;
      assumptions.push(`Billing Policy set to "${ctx.productBillingPolicy.name}" — the policy ${product.name} already uses (Product → Billing Policy).`);
    }
    const chosenPolicy = draft.references.BillingPolicyId;
    const defaultLink = links.find(l => l.sobject === "BillingPolicy" && l.field === "DefaultBillingTreatmentId");
    if (chosenPolicy && defaultLink && ctx.productBillingPolicy?.id === chosenPolicy.id) {
      addTarget(defaultLink, chosenPolicy);
      warnings.push(`${product.name} bills with "${chosenPolicy.name}"'s default treatment${ctx.productDefaultTreatment ? ` ("${ctx.productDefaultTreatment.name}")` : ""}. Enable "${defaultLink.label}" if this new treatment should replace it.`);
    }
    if (productLink && (!ctx.productBillingPolicy || (chosenPolicy && ctx.productBillingPolicy.id !== chosenPolicy.id))) {
      addTarget(productLink, product);
      warnings.push(ctx.productBillingPolicy
        ? `${product.name} uses a different Billing Policy ("${ctx.productBillingPolicy.name}"). Enable "${productLink.label}" to move it to the selected policy.`
        : `${product.name} has no Billing Policy yet — products only reach a treatment through a policy. Select a Billing Policy and enable "${productLink.label}".`);
    }
  }

  if (schema.moduleKey === "billing-treatment-items") {
    const tMeta = schema.fields.find(f => f.name === "BillingTreatmentId" && f.createable);
    if (tMeta && !has("BillingTreatmentId")) {
      if (ctx.productDefaultTreatment) {
        draft.references.BillingTreatmentId = ctx.productDefaultTreatment;
        assumptions.push(`Billing Treatment set to "${ctx.productDefaultTreatment.name}" — the default treatment of "${ctx.productBillingPolicy?.name}", ${product.name}'s Billing Policy (Product → Billing Policy → Default Treatment).`);
      } else {
        warnings.push(`Couldn't derive a Billing Treatment from ${product.name}: ${ctx.productBillingPolicy ? `its Billing Policy "${ctx.productBillingPolicy.name}" has no default treatment` : "it has no Billing Policy"}. Select the Billing Treatment this item belongs to.`);
      }
    }
  }
  return ctx;
}

/** Every unresolved lookup in the draft tree, with the child module that could be created inline to satisfy it. */
async function collectUnresolved(client: SalesforceClient, draft: BillingDraftRecord, path: string, out: BillingAnalysisResult["unresolvedReferences"]): Promise<void> {
  const schema = await getModuleSchema(client, draft.moduleKey).catch(() => null);
  for (const [field, u] of Object.entries(draft.unresolved ?? {})) {
    const meta = schema?.fields.find(f => f.name === field);
    const child = meta && !meta.required && meta.updateable ? schema?.children.find(c => meta.referenceTo.includes(c.sobject)) : undefined;
    out.push({ path, field, label: meta?.label ?? field, searchedName: u.searchedName, sobject: u.sobject, candidates: u.candidates, createAsChildModule: child?.moduleKey ?? null });
  }
  for (let i = 0; i < draft.children.length; i++) await collectUnresolved(client, draft.children[i], path ? `${path}.${i}` : String(i), out);
}

/**
 * Full analysis pipeline: Intent → Object identification → Field extraction →
 * Relationship resolution (live SOQL, incl. the product's billing chain) → Salesforce-required
 * values → Metadata validation → Draft. The draft is the SAME shape the manual form edits and the
 * create route accepts. Nothing is created here — the user reviews and edits it first.
 */
export async function analyzeBillingPrompt(client: SalesforceClient, anthropic: Anthropic, prompt: string, moduleKey: string, routing?: { confidence: number; reason: string }): Promise<BillingAnalysisResult> {
  const schema = await getModuleSchema(client, moduleKey);
  const def = getBillingModule(moduleKey)!;
  const children = await collectChildSchemas(client, schema, 0);
  const resolved = await resolveAllModules(client);
  const others = BILLING_MODULES.filter(m => m.key !== moduleKey && resolved.get(m.key)?.createable).map(m => `${resolved.get(m.key)!.sobject} (${m.singular})`);

  const todayISO = new Date().toISOString().slice(0, 10);
  const ai = await callClaude(anthropic, systemPrompt(schema, children, others, todayISO), prompt, 4096);

  const strings = (v: unknown) => (Array.isArray(v) ? v : []).filter((x): x is string => typeof x === "string");
  const warnings = strings(ai.warnings);
  const assumptions = strings(ai.assumptions);
  const intent = ai.intent === "unsupported" ? "unsupported" as const : "create" as const;
  const objectType = typeof ai.objectType === "string" ? ai.objectType : schema.sobject;
  const confidence = Math.max(0, Math.min(1, typeof ai.confidence === "number" ? ai.confidence : 0.5));

  let suggestedModuleKey: string | null = null;
  if (objectType.toLowerCase() !== schema.sobject.toLowerCase()) {
    const match = BILLING_MODULES.find(m => resolved.get(m.key)?.sobject.toLowerCase() === objectType.toLowerCase());
    if (match && match.key !== moduleKey) suggestedModuleKey = match.key;
  }

  const stats: NormalizeStats = { fieldsExtracted: 0, fieldsDropped: 0, refsResolved: 0, refsUnresolved: 0, idsRejected: 0 };
  const draft = await normalizeRecord(client, schema, ai as AiRecord, 0, warnings, stats);
  const links = await normalizeLinks(client, schema, ai.links, warnings);

  const unresolvedReferences: BillingAnalysisResult["unresolvedReferences"] = [];
  const rawContext = (ai.context && typeof ai.context === "object" ? ai.context : {}) as { productName?: unknown };
  const productName = typeof rawContext.productName === "string" && rawContext.productName.trim() ? rawContext.productName.trim() : null;
  const context: AnalysisContext = productName
    ? await applyProductContext(client, schema, draft, links, productName, warnings, assumptions, unresolvedReferences)
    : { productName: null, product: null, productBillingPolicy: null, productDefaultTreatment: null };

  // Names the model couldn't place on any real field — surfaced, never silently dropped.
  for (const u of (Array.isArray(ai.unresolvedReferences) ? ai.unresolvedReferences : []) as { name?: unknown; object?: unknown }[]) {
    if (typeof u?.name === "string" && u.name.trim()) warnings.push(`"${u.name}" was mentioned but doesn't map to a ${def.singular} field in this org${typeof u.object === "string" ? ` (${u.object})` : ""}.`);
  }

  await applyDefaultsTree(client, draft, null, assumptions);
  await collectUnresolved(client, draft, "", unresolvedReferences);
  const { result: validation } = await prepareAndValidate(client, draft, links);

  const countNodes = (d: BillingDraftRecord): number => 1 + d.children.reduce((n, c) => n + countNodes(c), 0);
  const errors = validation.issues.filter(i => i.severity === "error").length;
  const warnIssues = validation.issues.filter(i => i.severity === "warning").length;
  const found = validation.references.filter(r => r.status === "found").length;

  const pipeline: BillingAnalysisStep[] = [
    { id: "intent", label: "Intent Detection", status: intent === "create" ? "done" : "failed", detail: intent === "create" ? `Create ${def.singular}${routing ? ` (routed with ${Math.round(routing.confidence * 100)}% confidence${routing.reason ? `: ${routing.reason}` : ""})` : ""}` : "The request can't be expressed with the billing objects in this org." },
    { id: "object", label: "Billing Object Identification", status: suggestedModuleKey ? "warning" : "done", detail: suggestedModuleKey ? `Prompt looks like a ${getBillingModule(suggestedModuleKey)?.singular} rather than a ${def.singular}.` : `${def.singular} → ${schema.sobject}` },
    { id: "fields", label: "Field Extraction", status: stats.fieldsDropped ? "warning" : "done", detail: `${stats.fieldsExtracted} field value${stats.fieldsExtracted === 1 ? "" : "s"} extracted${stats.fieldsDropped ? `, ${stats.fieldsDropped} ignored` : ""}; ${countNodes(draft) - 1} child record${countNodes(draft) - 1 === 1 ? "" : "s"}` },
    { id: "relationships", label: "Salesforce Record Resolution", status: unresolvedReferences.length || stats.idsRejected ? "warning" : "done", detail: `${found} record${found === 1 ? "" : "s"} found in Salesforce${context.product ? ` (incl. product ${context.product.name})` : ""}${unresolvedReferences.length ? `, ${unresolvedReferences.length} unresolved` : ""}${stats.idsRejected ? `, ${stats.idsRejected} AI-supplied Id rejected` : ""}` },
    { id: "validation", label: "Salesforce Metadata Validation", status: errors ? "failed" : warnIssues ? "warning" : "done", detail: errors ? `${errors} blocking issue${errors > 1 ? "s" : ""} to fix` : warnIssues ? `${warnIssues} warning${warnIssues > 1 ? "s" : ""}` : "All checks passed" },
    { id: "config", label: "Form Populated", status: "done", detail: "Review and edit the fields below — nothing has been created yet." },
  ];

  return {
    success: true, intent, moduleKey, objectType: schema.sobject, confidence,
    summary: typeof ai.summary === "string" ? ai.summary : `${def.singular} configuration`,
    suggestedModuleKey, warnings, assumptions, draft, links, validation, pipeline, rawAi: ai,
    context, unresolvedReferences,
  };
}

/* ─────────────────────────── AI EDIT ─────────────────────────── */

function editSystemPrompt(schema: BillingModuleSchema, ctx: BillingEditContext, todayISO: string): string {
  const editable = schema.fields.filter(f => f.updateable && !f.system && !ctx.locks[f.name] && !f.calculated);
  const locked = schema.fields.filter(f => (f.createable || f.updateable) && !f.system && ctx.locks[f.name]);
  const currentValue = (f: BillingFieldMeta) => (f.type === "reference" ? (ctx.draft.references[f.name]?.name ?? "(none)") : JSON.stringify(ctx.draft.fields[f.name] ?? null));
  const linkText = ctx.links.map(l => `  - ${l.sobject}.${l.field} (${l.label}); currently linked: ${l.targets.map(t => t.name).join(", ") || "none"}`).join("\n") || "  (none)";
  const relatedText = ctx.related.map(r => `  - ${r.title}: ${r.records.map(x => `${x.name} [${x.status ?? "-"}]`).join(", ") || "none"}`).join("\n") || "  (none)";

  return `You are a Salesforce Revenue Cloud Billing configuration analyst. The user wants to CHANGE an EXISTING ${schema.label} record. Convert the request into structured changes. A human reviews and validates your output before anything is saved.

Today's date is ${todayISO}.

${DOMAIN_KNOWLEDGE}
- Status can go Draft -> Active, Active -> Inactive and Inactive -> Active. It can NEVER go back to Draft.
- A Billing Treatment can only be Active when it has an Active Treatment Item; items can only be edited while their treatment is Draft; an item can never be moved to another treatment.
- A Billing Policy can only be Active when its Default Billing Treatment is set and Active.

THE RECORD BEING EDITED: "${ctx.name}" (${schema.sobject}). Fields that CAN be changed, with their current values:
${editable.map(f => `${describeField(f)} | current: ${currentValue(f)}`).join("\n")}

Fields that CANNOT be changed right now (never output them): ${locked.map(f => `${f.name} (${ctx.locks[f.name]})`).join("; ") || "none"}

Related records (read-only context):
${relatedText}

Links you may change (records that point at this one):
${linkText}

Output ONLY one JSON object, no markdown, no commentary:
{
  "intent": "update" | "unsupported",
  "objectType": "${schema.sobject}",
  "confidence": 0.0-1.0,
  "summary": "one sentence describing the change",
  "changes": { "FieldApiName": newValue },
  "relationships": { "ReferenceFieldApiName": { "searchName": "record name exactly as the user said it" } },
  "links": [ { "sobject": "Product2", "field": "BillingPolicyId", "add": ["names to link"], "remove": ["names to unlink"] } ],
  "assumptions": [], "warnings": [],
  "unresolvedReferences": [ { "name": "a name the user mentioned that maps to no field above" } ]
}

RULES
- Include ONLY fields the user asked to change. Never repeat unchanged values. Never output a record Id (not even this record's). The application already knows which record is open.
- Reference changes go in "relationships" as NAMES; the application resolves them by querying Salesforce. Never assume a named record exists.
- Picklist values must be one of the listed values, spelled exactly. Use only field names listed as changeable.
- If the request asks for something Salesforce will not allow (for example back to Draft), do not output that change; explain it in "warnings".`;
}

/**
 * AI edit: current Salesforce record -> model proposes structured changes -> changes applied to the
 * record's REAL draft (updateable fields only, names resolved by SOQL, AI Ids rejected) -> the same
 * update validation a manual edit gets. Nothing is saved; the user reviews the populated form.
 */
export async function analyzeBillingEdit(client: SalesforceClient, anthropic: Anthropic, prompt: string, moduleKey: string, recordId: string): Promise<BillingAnalysisResult> {
  const schema = await getModuleSchema(client, moduleKey);
  const def = getBillingModule(moduleKey)!;
  const ctx = await loadEditContext(client, moduleKey, recordId);
  const ai = await callClaude(anthropic, editSystemPrompt(schema, ctx, new Date().toISOString().slice(0, 10)), prompt, 2048);

  const strings = (v: unknown) => (Array.isArray(v) ? v : []).filter((x): x is string => typeof x === "string");
  const warnings = strings(ai.warnings);
  const assumptions = strings(ai.assumptions);
  const draft: BillingDraftRecord = { ...ctx.draft, fields: { ...ctx.draft.fields }, references: { ...ctx.draft.references }, unresolved: {} };
  const links = ctx.links.map(l => ({ ...l, targets: [...l.targets] }));
  const byName = new Map(schema.fields.map(f => [f.name.toLowerCase(), f]));
  let extracted = 0, dropped = 0, idsRejected = 0;

  if (typeof ai.recordId === "string" && ai.recordId.slice(0, 15) !== recordId.slice(0, 15)) warnings.push("The AI referred to a different record Id; it was ignored. Changes apply only to the record you opened.");

  const rawChanges = (ai.changes && typeof ai.changes === "object" ? ai.changes : {}) as Record<string, unknown>;
  const rawRels = { ...((ai.relationships && typeof ai.relationships === "object" ? ai.relationships : {}) as Record<string, unknown>) };
  for (const [name, value] of Object.entries(rawChanges)) {
    const f = byName.get(name.toLowerCase());
    if (!f) { warnings.push(`Ignored "${name}": no such field on ${schema.label} in this org.`); dropped++; continue; }
    if (f.type === "reference") { rawRels[f.name] = typeof value === "string" ? { searchName: value } : value; continue; }
    if (ctx.locks[f.name] || !f.updateable) { warnings.push(`${f.label} can't be changed: ${ctx.locks[f.name] ?? "Salesforce doesn't allow updating it."}`); dropped++; continue; }
    const c = coerceFieldValue(f, value);
    if (!c.ok) { warnings.push(`${schema.label}: ${c.reason}`); dropped++; continue; }
    draft.fields[f.name] = c.value;
    extracted++;
  }
  for (const [name, value] of Object.entries(rawRels)) {
    const f = byName.get(name.toLowerCase());
    if (!f || f.type !== "reference") { warnings.push(`Ignored relationship "${name}": not a lookup on ${schema.label}.`); continue; }
    if (ctx.locks[f.name] || !f.updateable) { warnings.push(`${f.label} can't be changed: ${ctx.locks[f.name] ?? "Salesforce doesn't allow updating it."}`); dropped++; continue; }
    const spec = (typeof value === "string" ? { searchName: value } : value) as { searchName?: unknown; name?: unknown } | null;
    const searched = typeof spec?.searchName === "string" ? spec.searchName.trim() : typeof spec?.name === "string" ? spec.name.trim() : "";
    if (!searched) continue;
    if (SALESFORCE_ID.test(searched) && /0{2,}/.test(searched)) { idsRejected++; warnings.push(`The AI returned a raw Id for ${f.label}; Ids are never trusted from AI output. Pick the record with the lookup.`); continue; }
    const target = f.referenceTo[0];
    const r = await resolveReferenceByName(client, target, searched).catch(() => null);
    if (r?.outcome === "resolved") { draft.references[f.name] = r.match; extracted++; }
    else draft.unresolved![f.name] = { searchedName: searched, sobject: target, candidates: r?.candidates ?? [] };
  }
  for (const req of (Array.isArray(ai.links) ? ai.links : []) as { sobject?: unknown; field?: unknown; add?: unknown; remove?: unknown }[]) {
    const link = links.find(l => l.sobject === req.sobject && l.field === req.field);
    if (!link) continue;
    const noun = link.sobject === "Product2" ? "Product" : link.sobject;
    for (const n of strings(req.add)) {
      const r = await resolveReferenceByName(client, link.sobject, n).catch(() => null);
      if (r?.outcome === "resolved") { if (!link.targets.some(t => t.id === r.match.id)) link.targets.push(r.match); extracted++; }
      else warnings.push(`${noun} "${n}" ${r?.outcome === "ambiguous" ? `matched ${r.candidates.length} records; add the right one manually` : "was not found in Salesforce"}.`);
    }
    for (const n of strings(req.remove)) {
      const before = link.targets.length;
      link.targets = link.targets.filter(t => !t.name.toLowerCase().includes(n.toLowerCase()));
      if (link.targets.length === before) warnings.push(`"${n}" isn't currently linked, so there is nothing to unlink.`); else extracted++;
    }
  }
  for (const u of (Array.isArray(ai.unresolvedReferences) ? ai.unresolvedReferences : []) as { name?: unknown }[]) {
    if (typeof u?.name === "string" && u.name.trim()) warnings.push(`"${u.name}" was mentioned but doesn't map to a ${def.singular} field in this org.`);
  }
  if (Object.keys(draft.unresolved!).length === 0) delete draft.unresolved;

  const { result: validation } = await prepareUpdate(client, moduleKey, recordId, draft, links);
  const unresolvedReferences: BillingAnalysisResult["unresolvedReferences"] = Object.entries(draft.unresolved ?? {}).map(([field, u]) => ({
    path: "", field, label: schema.fields.find(f => f.name === field)?.label ?? field, searchedName: u.searchedName, sobject: u.sobject, candidates: u.candidates, createAsChildModule: null,
  }));
  const errors = validation.issues.filter(i => i.severity === "error").length;
  const found = validation.references.filter(r => r.status === "found").length;
  const pipeline: BillingAnalysisStep[] = [
    { id: "intent", label: "Intent Detection", status: ai.intent === "unsupported" ? "failed" : "done", detail: ai.intent === "unsupported" ? "The request can't be expressed as a change to this record." : `Update ${def.singular} "${ctx.name}"` },
    { id: "object", label: "Record", status: "done", detail: `${schema.sobject} ${recordId} (the record you opened, never taken from the AI)` },
    { id: "fields", label: "Change Extraction", status: dropped ? "warning" : "done", detail: `${extracted} change${extracted === 1 ? "" : "s"} applied to the form${dropped ? `, ${dropped} ignored` : ""}` },
    { id: "relationships", label: "Salesforce Record Resolution", status: unresolvedReferences.length || idsRejected ? "warning" : "done", detail: `${found} record${found === 1 ? "" : "s"} verified${unresolvedReferences.length ? `, ${unresolvedReferences.length} unresolved` : ""}${idsRejected ? `, ${idsRejected} AI Id rejected` : ""}` },
    { id: "validation", label: "Change Validation", status: errors ? "failed" : "done", detail: errors ? `${errors} blocking issue${errors > 1 ? "s" : ""}` : validation.transition ? (validation.transition.ready ? `Status ${validation.transition.from} -> ${validation.transition.to}: ready` : "Status change blocked") : "All checks passed" },
    { id: "config", label: "Form Updated", status: "done", detail: "Review the highlighted changes below. Nothing has been saved." },
  ];

  return {
    success: true, intent: ai.intent === "unsupported" ? "unsupported" : "update", recordId, moduleKey, objectType: schema.sobject,
    confidence: Math.max(0, Math.min(1, typeof ai.confidence === "number" ? ai.confidence : 0.5)),
    summary: typeof ai.summary === "string" ? ai.summary : `Changes to ${ctx.name}`,
    suggestedModuleKey: null, warnings, assumptions, draft, links, validation, pipeline, rawAi: ai,
    context: { productName: null, product: null, productBillingPolicy: null, productDefaultTreatment: null },
    unresolvedReferences, changes: validation.changes ?? [],
  };
}
